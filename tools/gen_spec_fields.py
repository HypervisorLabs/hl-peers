#!/usr/bin/env python3
"""Derive spec/peer-api-v1.fields.json from the vendored public OpenAPI.

The four clients' models are hand-shaped (idiomatic public surface), but each
client has a test asserting its typed models cover EXACTLY these field sets, so
spec drift fails a build instead of silently landing in `extra`.

    python3 tools/gen_spec_fields.py          # rewrite
    python3 tools/gen_spec_fields.py --check  # exit 1 if stale (CI)

Needs PyYAML (dev only).
"""
import json
import os
import re
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPEC = os.path.join(ROOT, "spec", "peer-api-v1.openapi.yaml")
OUT = os.path.join(ROOT, "spec", "peer-api-v1.fields.json")


def props(schema):
    return sorted(schema.get("properties", {}))


def all_of_props(schema):
    out = set()
    for part in schema.get("allOf", []):
        out.update(part.get("properties", {}))
    return sorted(out)


# Served by the live API but not (yet) in the upstream `NetworkMapSummary`
# schema: the summary carries the same `cities` / `attribution` as the graph.
# CLIENT_SPEC.md §10 D-S. Delete this when upstream's schema lists them.
SUMMARY_SERVED_NOT_IN_SPEC = {"attribution", "cities"}


def param_name(spec, p):
    if "name" in p:
        return p["name"]
    return spec["components"]["parameters"][p["$ref"].rsplit("/", 1)[1]]["name"]


def param_enum(spec, key):
    """CSV-of-closed-enum parameters carry their members in a `^(a|b)(,(a|b))*$` pattern."""
    sch = spec["components"]["parameters"][key]["schema"]
    if "enum" in sch:
        return sch["enum"]
    m = re.match(r"^\^\(([^)]*)\)", sch["pattern"])
    return m.group(1).split("|")


def state_enum(spec):
    desc = spec["components"]["parameters"]["State"]["description"]
    head = desc.split(".")[0]
    return re.findall(r"`([a-z_]+)`", head)


def build():
    spec = yaml.safe_load(open(SPEC, encoding="utf-8"))
    sc = spec["components"]["schemas"]
    paths = spec["paths"]

    def qparams(path):
        return sorted(
            {param_name(spec, p) for p in paths[path]["get"]["parameters"]} - {"If-None-Match"}
        )

    return {
        "_comment": "GENERATED by tools/gen_spec_fields.py from spec/peer-api-v1.openapi.yaml. Do not edit.",
        "peer": props(sc["Peer"]),
        "peer_mempool": props(sc["MempoolSignal"]),
        "peer_auction": props(sc["AuctionSignal"]),
        "envelope": props(sc["Envelope"]),
        "peer_list": sorted(set(props(sc["Envelope"])) | set(all_of_props(sc["PeerList"]))),
        "facets": sorted(set(props(sc["Envelope"])) | set(all_of_props(sc["Facets"]))),
        "list_peers_params": qparams("/peers"),
        "facets_params": qparams("/peers/facets"),
        "network_map_params": qparams("/network-map/graph"),
        "network_map_graph": props(sc["NetworkMapGraph"]),
        "network_map_summary": sorted(set(props(sc["NetworkMapSummary"])) | SUMMARY_SERVED_NOT_IN_SPEC),
        "network_map_edge": props(sc["NetworkMapEdge"]),
        "network_map_city": props(sc["CityCluster"]),
        "enums": {
            "state": state_enum(spec),
            "connectable": ["yes", "no", "unknown"],
            "serves_mempool": param_enum(spec, "ServesMempool"),
            "auction": param_enum(spec, "Auction"),
            "sort": spec["components"]["parameters"]["Sort"]["schema"]["enum"],
            "format": spec["components"]["parameters"]["Format"]["schema"]["enum"],
            "chain": spec["components"]["parameters"]["Chain"]["schema"]["enum"],
        },
    }


def main():
    text = json.dumps(build(), indent=2) + "\n"
    if "--check" in sys.argv:
        if open(OUT, encoding="utf-8").read() != text:
            print("spec/peer-api-v1.fields.json is stale: run tools/gen_spec_fields.py")
            return 1
        print("fields OK")
        return 0
    open(OUT, "w", encoding="utf-8").write(text)
    print("wrote", os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
