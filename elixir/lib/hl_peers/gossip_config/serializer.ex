defmodule HlPeers.GossipConfig.Serializer do
  @moduledoc """
  The byte-exact `override_gossip_config.json` renderer of `CLIENT_SPEC.md` §6.3.

  Four independent implementations must produce the identical byte string for
  the identical logical input, so nothing here is left to a JSON library's
  defaults — `Jason`'s encoder gives neither the key order nor the separators
  this file needs, so the rendering is written out longhand.

  The rules, restated:

  1. known keys first, in the fixed order
     `chain`, `root_node_ips`, `try_new_peers`, `reserved_peer_ips`,
     `n_gossip_peers`, `split_client_blocks`; absent keys are skipped;
  2. unknown keys after them, sorted by Unicode code point, recursively
     (nested object keys sort, array order is preserved);
  3. 2-space nesting-proportional indent, `","` between items, `": "` between
     key and value;
  4. non-empty arrays and objects expand across lines; an empty array is `[]`
     and an empty object is `{}`, inline;
  5. exactly one trailing `\\n`, never `\\r\\n`;
  6. non-ASCII is emitted literally as UTF-8, with RFC 8259 minimal escaping
     (`"`, `\\` and C0 controls only — `/` is not escaped);
  7. integers carry no decimal point or exponent.

  This is exactly the output of Python's
  `json.dumps(obj, indent=2, ensure_ascii=False, separators=(",", ": ")) + "\\n"`
  under the key ordering of (1)+(2), which is the reference implementation in
  `tools/gen_fixtures.py` the fixtures were generated by.
  """

  @known_order ~w(chain root_node_ips try_new_peers reserved_peer_ips n_gossip_peers split_client_blocks)

  @doc "The fixed key order for known keys (`CLIENT_SPEC.md` §6.3(1))."
  @spec known_order() :: [String.t()]
  def known_order, do: @known_order

  @doc """
  Renders a decoded config map to the normative byte string.

      iex> HlPeers.GossipConfig.Serializer.render(%{
      ...>   "root_node_ips" => [%{"Ip" => "192.0.2.10"}],
      ...>   "chain" => "Mainnet"
      ...> })
      "{\\n  \\"chain\\": \\"Mainnet\\",\\n  \\"root_node_ips\\": [\\n    {\\n      \\"Ip\\": \\"192.0.2.10\\"\\n    }\\n  ]\\n}\\n"
  """
  @spec render(map()) :: String.t()
  def render(config) when is_map(config) do
    IO.iodata_to_binary([encode(ordered_pairs(config), 0), "\n"])
  end

  defp ordered_pairs(config) do
    known = for k <- @known_order, Map.has_key?(config, k), do: {k, Map.fetch!(config, k)}

    unknown =
      config
      |> Map.drop(@known_order)
      |> Enum.sort_by(fn {k, _} -> k end, &code_point_le/2)

    {:pairs, known ++ unknown}
  end

  # Erlang's default binary ordering IS code-point order for UTF-8, so plain
  # `<=` is the sort the spec asks for. Named for the intent.
  defp code_point_le(a, b), do: a <= b

  defp encode({:pairs, []}, _depth), do: "{}"

  defp encode({:pairs, pairs}, depth) do
    inner = indent(depth + 1)

    body =
      pairs
      |> Enum.map(fn {k, v} -> [inner, string(to_string(k)), ": ", encode(v, depth + 1)] end)
      |> Enum.intersperse(",\n")

    ["{\n", body, "\n", indent(depth), "}"]
  end

  defp encode(value, depth) when is_map(value) do
    value
    |> Enum.sort_by(fn {k, _} -> to_string(k) end, &code_point_le/2)
    |> then(&encode({:pairs, &1}, depth))
  end

  defp encode([], _depth), do: "[]"

  defp encode(list, depth) when is_list(list) do
    inner = indent(depth + 1)

    body =
      list
      |> Enum.map(&[inner, encode(&1, depth + 1)])
      |> Enum.intersperse(",\n")

    ["[\n", body, "\n", indent(depth), "]"]
  end

  defp encode(nil, _depth), do: "null"
  defp encode(true, _depth), do: "true"
  defp encode(false, _depth), do: "false"
  defp encode(value, _depth) when is_integer(value), do: Integer.to_string(value)

  # No float appears in this schema; a float inside an unknown key is re-emitted
  # with the shortest round-trip representation (§6.3(7)).
  defp encode(value, _depth) when is_float(value), do: Float.to_string(value)
  defp encode(value, _depth) when is_binary(value), do: string(value)
  defp encode(value, _depth) when is_atom(value), do: string(Atom.to_string(value))

  defp indent(0), do: ""
  defp indent(depth), do: String.duplicate("  ", depth)

  defp string(s), do: [?", escape(s, []), ?"]

  defp escape(<<>>, acc), do: Enum.reverse(acc)
  defp escape(<<?", rest::binary>>, acc), do: escape(rest, ["\\\"" | acc])
  defp escape(<<?\\, rest::binary>>, acc), do: escape(rest, ["\\\\" | acc])
  defp escape(<<?\b, rest::binary>>, acc), do: escape(rest, ["\\b" | acc])
  defp escape(<<?\f, rest::binary>>, acc), do: escape(rest, ["\\f" | acc])
  defp escape(<<?\n, rest::binary>>, acc), do: escape(rest, ["\\n" | acc])
  defp escape(<<?\r, rest::binary>>, acc), do: escape(rest, ["\\r" | acc])
  defp escape(<<?\t, rest::binary>>, acc), do: escape(rest, ["\\t" | acc])

  defp escape(<<c::utf8, rest::binary>>, acc) when c < 0x20 do
    escape(rest, ["\\u" <> (c |> Integer.to_string(16) |> String.downcase() |> pad4()) | acc])
  end

  defp escape(<<c::utf8, rest::binary>>, acc), do: escape(rest, [<<c::utf8>> | acc])

  defp pad4(hex), do: String.pad_leading(hex, 4, "0")
end
